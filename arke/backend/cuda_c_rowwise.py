def _emit_simple_reduce(graph: IRGraph, chip: str, op: str, init: str, combine: str, finalize: str) -> CudaCKernel:
    node = graph.nodes[0]
    assert node.op == op
    x_name = list(node.inputs.values())[0]
    out_name = node.outputs[0]
    x_val = graph.get_value(x_name)
    shape = list(x_val.shape)
    M, N = shape[0], shape[1]
    dtype = x_val.dtype or "float32"
    c_type = _ir_dtype_to_c(dtype)
    blk = rowwise_block_for_n(N)
    kernel_name = f"arke_{op}_{M}x{N}"

    source = f"""\
// Auto-generated by Arke CudaCBackend — rowwise {op}
#include <cuda_runtime.h>
#include <math.h>

extern "C"
__global__ void {kernel_name}(
    const {c_type}* __restrict__ X,
    {c_type}* __restrict__ Out,
    int M, int N)
{{
    __shared__ {c_type} sdata[{blk}];
    int row = blockIdx.x;
    int tid = threadIdx.x;

    {c_type} acc = {init};
    for (int j = tid; j < N; j += {blk}) {{
        {c_type} v = X[row * N + j];
        {combine}
    }}
    sdata[tid] = acc;
    __syncthreads();
    for (int s = {blk}/2; s > 0; s >>= 1) {{
        if (tid < s) {{ {c_type} other = sdata[tid + s]; {combine.replace('v', 'other')} sdata[tid] = acc; }}
        __syncthreads();
    }}
    if (tid == 0) {{
        {c_type} acc = sdata[0];
        Out[row] = {finalize};
    }}
}}
"""
    return CudaCKernel(
        kernel_name=kernel_name, source=source, op_name=op,
        param_names=[x_name, out_name], output_name=out_name,
        shapes={x_name: [M, N], out_name: [M, 1]},
        dtypes={x_name: dtype, out_name: dtype},
        grid=(M, 1, 1), block=(blk, 1, 1),
        shared_mem=0,
        kernel_args=[("ptr", x_name), ("ptr", out_name), ("int", M), ("int", N)],
    )


