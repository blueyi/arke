"""Rowwise reduction CUDA-C emitters for CudaCBackend (Phase 4).

Ops: softmax, layernorm, rmsnorm, reduce_sum, reduce_max, reduce_mean.
Each kernel uses 1 block per row, 256 threads, shared-memory tree reduction.
"""

from __future__ import annotations

from arke.backend.cuda_c_backend import CudaCKernel, _ir_dtype_to_c
from arke.ir.graph import IRGraph

BLOCK = 256


def rowwise_block_for_n(N: int) -> int:
    """Shape-adaptive block size for rowwise (1-block-per-row) kernels.

    Empirically (RTX 3060, softmax N=4096): BLOCK=512 gives 1.13× cuBLAS vs
    0.66× at BLOCK=256 and 0.68× at BLOCK=1024. At large N the extra threads
    cut per-thread element count and improve memory throughput; BLOCK=1024
    over-subscribes and drops occupancy. Small N keeps 256 (fewer wasted
    threads, shallower tree-reduce).

    Policy: N >= 2048 → 512, else 256. (Matches the MLIR backend's
    rowwise_block_size philosophy, tuned for the CUDA-C 3-pass kernels.)
    """
    return 512 if N >= 2048 else 256


def emit_cuda_c_softmax(graph: IRGraph, chip: str = "sm_86") -> CudaCKernel:
    node = graph.nodes[0]
    assert node.op == "softmax"
    x_name = list(node.inputs.values())[0]
    out_name = node.outputs[0]
    x_val = graph.get_value(x_name)
    shape = list(x_val.shape)
    M, N = shape[0], shape[1]
    dtype = x_val.dtype or "float32"
    c_type = _ir_dtype_to_c(dtype)
    blk = rowwise_block_for_n(N)
    kernel_name = f"arke_softmax_{M}x{N}"

    source = f"""\
// Auto-generated by Arke CudaCBackend — rowwise softmax (block={blk})
#include <cuda_runtime.h>
#include <math.h>

extern "C"
__global__ void {kernel_name}(
    const {c_type}* __restrict__ X,
    {c_type}* __restrict__ Out,
    int M, int N)
{{
    __shared__ {c_type} sdata[{blk}];
    int row = blockIdx.x;
    int tid = threadIdx.x;

    // 1) find row max
    {c_type} mx = -1e30f;
    for (int j = tid; j < N; j += {blk}) {{
        {c_type} v = X[row * N + j];
        if (v > mx) mx = v;
    }}
    sdata[tid] = mx;
    __syncthreads();
    for (int s = {blk}/2; s > 0; s >>= 1) {{
        if (tid < s && sdata[tid + s] > sdata[tid]) sdata[tid] = sdata[tid + s];
        __syncthreads();
    }}
    {c_type} row_max = sdata[0];
    __syncthreads();

    // 2) compute exp and sum
    {c_type} sum_val = 0.0f;
    for (int j = tid; j < N; j += {blk}) {{
        {c_type} e = expf(X[row * N + j] - row_max);
        Out[row * N + j] = e;
        sum_val += e;
    }}
    sdata[tid] = sum_val;
    __syncthreads();
    for (int s = {blk}/2; s > 0; s >>= 1) {{
        if (tid < s) sdata[tid] += sdata[tid + s];
        __syncthreads();
    }}
    {c_type} row_sum = sdata[0];
    __syncthreads();

    // 3) normalize
    for (int j = tid; j < N; j += {blk}) {{
        Out[row * N + j] /= row_sum;
    }}
}}
"""
    return CudaCKernel(
        kernel_name=kernel_name, source=source, op_name="softmax",
        param_names=[x_name, out_name], output_name=out_name,
        shapes={x_name: [M, N], out_name: [M, N]},
        dtypes={x_name: dtype, out_name: dtype},
        grid=(M, 1, 1), block=(blk, 1, 1),
        shared_mem=0,
        kernel_args=[("ptr", x_name), ("ptr", out_name), ("int", M), ("int", N)],
    )


def emit_cuda_c_layernorm(graph: IRGraph, chip: str = "sm_86") -> CudaCKernel:
    node = graph.nodes[0]
    assert node.op == "layernorm"
    x_name = list(node.inputs.values())[0]
    w_name = list(node.inputs.values())[1]
    b_name = list(node.inputs.values())[2]
    out_name = node.outputs[0]
    x_val = graph.get_value(x_name)
    shape = list(x_val.shape)
    M, N = shape[0], shape[1]
    dtype = x_val.dtype or "float32"
    c_type = _ir_dtype_to_c(dtype)
    blk = rowwise_block_for_n(N)
    kernel_name = f"arke_layernorm_{M}x{N}"

    source = f"""\
// Auto-generated by Arke CudaCBackend — rowwise layernorm
#include <cuda_runtime.h>
#include <math.h>

extern "C"
__global__ void {kernel_name}(
    const {c_type}* __restrict__ X,
    const {c_type}* __restrict__ W,
    const {c_type}* __restrict__ B,
    {c_type}* __restrict__ Out,
    int M, int N)
{{
    __shared__ {c_type} sdata[{blk}];
    int row = blockIdx.x;
    int tid = threadIdx.x;

    // mean
    {c_type} sum_val = 0.0f;
    for (int j = tid; j < N; j += {blk}) sum_val += X[row * N + j];
    sdata[tid] = sum_val;
    __syncthreads();
    for (int s = {blk}/2; s > 0; s >>= 1) {{
        if (tid < s) sdata[tid] += sdata[tid + s];
        __syncthreads();
    }}
    {c_type} mean = sdata[0] / ({c_type})N;
    __syncthreads();

    // variance
    {c_type} var_val = 0.0f;
    for (int j = tid; j < N; j += {blk}) {{
        {c_type} d = X[row * N + j] - mean;
        var_val += d * d;
    }}
    sdata[tid] = var_val;
    __syncthreads();
    for (int s = {blk}/2; s > 0; s >>= 1) {{
        if (tid < s) sdata[tid] += sdata[tid + s];
        __syncthreads();
    }}
    {c_type} inv_std = rsqrtf(sdata[0] / ({c_type})N + 1e-5f);
    __syncthreads();

    // normalize + affine
    for (int j = tid; j < N; j += {blk}) {{
        Out[row * N + j] = (X[row * N + j] - mean) * inv_std * W[j] + B[j];
    }}
}}
"""
    return CudaCKernel(
        kernel_name=kernel_name, source=source, op_name="layernorm",
        param_names=[x_name, w_name, b_name, out_name], output_name=out_name,
        shapes={x_name: [M, N], w_name: [N], b_name: [N], out_name: [M, N]},
        dtypes={x_name: dtype, w_name: dtype, b_name: dtype, out_name: dtype},
        grid=(M, 1, 1), block=(blk, 1, 1),
        shared_mem=0,
        kernel_args=[("ptr", x_name), ("ptr", w_name), ("ptr", b_name), ("ptr", out_name), ("int", M), ("int", N)],
    )


